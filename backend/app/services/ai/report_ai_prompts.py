def build_summary_from_notes_prompt(
    title: str,
    analysis_notes: str,
) -> str:
    return f"""
你正在根据一篇国际关系智库报告的全文分块分析笔记，
生成评论稿第一部分“主要观点”。

这些分析笔记已经按报告正文顺序覆盖整篇报告。
你必须综合所有部分，而不能只关注前面的内容。

验收标准：
- summary 最终会按中文字符数校验，必须达到 1500-2200 字符。
- 为提高通过率，建议写到 1800-2000 字符，不要贴近上下限。
- 请写 4 个及以上分论点段落，每段约 450-500 个中文字符。
- 每个分论点必须使用中文序号开头，例如“一、……”“二、……”
  “三、……”“四、……”，序号后直接写该分论点的小标题和展开分析。
- 这一部分是正式评论稿的主要观点部分，不要写成简短提纲。

你必须只输出一个 JSON 对象。

禁止：
- 不要 Markdown
- 不要使用无编号的连续段落
- 不要 ```json
- 不要解释 JSON
- 不要虚构分析笔记中不存在的信息
- 不要简单逐块复述
- 不要重复相同观点
- 不要把不同部分中的重复事实反复列出
- 如果不同笔记存在表述差异，应根据整体上下文谨慎综合，
  不要擅自制造新的事实

JSON 必须严格为：

{{
  "summary": "生成1800-2000字符的评论稿第一部分：主要观点，硬性合格范围为1500-2200字符。必须包含4个及以上主要观点，每个观点单独成段，每段约450-500个中文字符，并必须依次使用“一、”“二、”“三、”“四、”等中文序号开头。每个序号后先写该观点的小标题，再展开事实、逻辑和结论。应覆盖整篇报告的研究背景、核心论点、重要事实或案例、政策建议与主要结论，并按照报告整体逻辑组织，而不是简单拼接分块笔记。"
}}

报告标题：
{title}

全文分析笔记：
{analysis_notes}
""".strip()


def build_commentary_from_notes_prompt(
    title: str,
    analysis_notes: str,
) -> str:
    return f"""
你正在根据一篇国际关系智库报告的全文分块分析笔记，
生成评论稿第二部分“深层研判”。

这些分析笔记已经覆盖整篇报告。
你需要在准确理解报告原意的基础上进行综合判断。

验收标准：
- commentary 最终会按中文字符数校验，必须达到 2000-2500 字符。
- 为提高通过率，建议写到 2300-2400 字符，不要贴近上下限。
- 请写 4 个及以上分论点段落，建议写到 5 个，每段约 430-500 个中文字符。
- 每个分论点必须使用中文序号开头，例如“一、……”“二、……”
  “三、……”“四、……”“五、……”，序号后直接写该分论点的小标题和展开研判。
- 不要写成短评或提纲，必须展开深层机制、政策意图和趋势判断。

你必须只输出一个 JSON 对象。

禁止：
- 不要 Markdown
- 不要使用无编号的连续段落
- 不要 ```json
- 不要解释 JSON
- 不要虚构报告或分析笔记中不存在的事实
- 不要简单重复“主要观点”部分
- 不要逐块机械复述分析笔记
- 如果原报告并不直接涉及中国，
  不要虚构“中国受到直接影响”的事实；
  可以在明确标明分析性质的前提下讨论其潜在战略启示

JSON 必须严格为：

{{
  "commentary": "生成2300-2400字符的评论稿第二部分：深层研判，硬性合格范围为2000-2500字符。必须包含4个及以上分论点，建议写到5个，每个分论点单独成段，每段约450-500个中文字符，并必须依次使用“一、”“二、”“三、”“四、”等中文序号开头；如写第五个分论点，继续使用“五、”。每个序号后先写该研判的小标题，再展开机制、意图、影响和趋势判断。必须分析：1. 报告主要观点及其逻辑；2. 报告所反映的政策或战略意图；3. 对中国及国际格局的现实或潜在影响；4. 未来趋势、深层政策问题或国际竞争问题；5. 报告未明说但可从其叙事方式、证据选择或政策建议中看出的深层问题。评论必须建立在全文分析笔记基础上，并区分报告原文观点与进一步战略研判。"
}}

报告标题：
{title}

全文分析笔记：
{analysis_notes}
""".strip()


def append_length_retry_feedback(
    prompt: str,
    *,
    field: str,
    min_chars: int,
    max_chars: int,
    last_error: Exception | None,
    previous_draft: str | None = None,
) -> str:
    if last_error is None:
        return prompt

    default_target_ranges = {
        "summary": "1800-2000",
        "commentary": "2300-2400",
    }
    preferred_range = default_target_ranges.get(
        field,
        f"{min_chars}-{max_chars}",
    )

    draft_section = ""

    if previous_draft:
        draft_section = f"""

上一版 {field} 草稿如下，请在保留其核心判断的基础上扩写，
不要推翻重写，也不要压缩已有内容：
{previous_draft}
""".rstrip()

    error_text = str(last_error)

    point_requirement = "4个及以上中文编号分论点"

    if "长度超出" in error_text:
        if field == "commentary":
            preferred_range = "2200-2300"

        adjustment = (
            f"请压缩冗余表述，保留{point_requirement}和核心判断，"
            "把每段控制得更紧凑，使最终结果回到目标区间。"
            "如果上一版明显过长，请删去约20%的重复背景和排比句，"
            "不要新增第六个以上分论点。"
        )
    else:
        if field == "commentary":
            preferred_range = "2300-2400"

        adjustment = (
            f"请显著扩写每个中文编号分论点，确保包含{point_requirement}，"
            "补充因果链条、政策背景、"
            "事实依据和战略含义。每个分论点都必须增加实质性解释，"
            "不要只补一句结论，避免再次低于下限。"
        )

    return f"""
{prompt}

上一次生成未通过长度校验：
{type(last_error).__name__}: {last_error}
{draft_section}

请重新生成 {field} 字段，必须达到 {min_chars}-{max_chars} 个中文字符。
为避免再次贴近边界，建议控制在 {preferred_range} 个中文字符。
{adjustment}
必须显式使用“一、”“二、”“三、”“四、”等中文序号组织分论点；
如果生成 commentary 字段，建议写到“五、”，但至少必须写满四个编号分论点。
不能输出无编号的连续段落。
如果上一版只是略短，请优先补足分析深度；如果上一版超出上限，
请删去重复铺陈和空泛句，保留最关键的事实、逻辑和研判。
仍然只能输出一个 JSON 对象，不能输出解释。
""".strip()


def append_translation_retry_feedback(
    prompt: str,
    *,
    min_chars: int,
    max_chars: int,
    last_error: Exception | None,
) -> str:
    if last_error is None:
        return prompt

    error_text = str(last_error)

    if "长度超出" in error_text:
        adjustment = (
            "上一版明显过长，通常是把目录、标题或清单扩写成了解释性内容。"
            "请只翻译当前输入中实际存在的文字，不要补充说明、背景、页码解释、"
            "政策解读或任何原文没有的内容。"
        )
    else:
        adjustment = (
            "请逐段补足漏译内容，但仍然不要扩写或添加原文没有的信息。"
        )

    return f"""
{prompt}

上一次翻译未通过完整性验收：
{type(last_error).__name__}: {last_error}

请重新执行全文翻译。必须逐段翻译当前输入正文，
不得改写为摘要、要点、提纲或评论。
本次译文应控制在 {min_chars}-{max_chars} 个中文字符之间。
{adjustment}
""".strip()


def build_translation_prompt(
    title: str,
    content: str,
) -> str:
    return f"""
你现在执行的是“全文翻译任务”，不是摘要、概括、分析或评论任务。

请将下面提供的英文智库报告正文完整翻译成中文。

必须严格遵守以下要求：

1. 必须逐段完整翻译输入正文，不得摘要、概括、压缩、删减或跳过任何实质性内容。
2. 必须保留原文的信息量、论证过程、事实、数据、案例、机构名称、人名、地名、时间、数字以及政策表述。
3. 必须尽量保持原文的标题、章节、小标题、段落和列举结构。
4. 不得因为某一段看起来重复、次要或属于背景介绍而省略。
5. 不得自行增加原文中不存在的观点、解释、评论或结论。
6. 专有名词首次出现时，可采用“中文译名（英文原名）”；后续可使用中文译名。
7. 输入内容只是整篇报告的一个分块，也必须完整翻译当前分块，不要尝试总结整篇报告。
8. 如果输入在句子中间开始或结束，只翻译实际提供的内容，不得自行补写缺失上下文。

你必须只输出中文译文正文。

禁止：
- 不要 Markdown
- 不要 ```
- 不要解释任务
- 不要输出摘要
- 不要输出分析
- 不要输出评论
- 不要输出 JSON
- 不要添加“以下是翻译”等说明性文字

报告标题：
{title}

需要完整翻译的正文：
{content}
""".strip()


def build_analysis_notes_prompt(
    title: str,
    content: str,
    chunk_index: int,
    chunk_count: int,
) -> str:
    return f"""
你正在阅读一篇国际关系智库报告的第
{chunk_index}/{chunk_count} 部分。

你的任务不是生成最终摘要或评论，
而是提取这一部分中值得保留的事实、论点和证据，
供后续对整篇报告进行综合分析。

你必须只输出一个 JSON 对象。

禁止：
- 不要 Markdown
- 不要 ```json
- 不要解释 JSON
- 不要虚构报告未提供的信息
- 不要把这一部分误当成整篇报告
- 不要输出 JSON 之外的内容

JSON 必须严格为：

{{
  "analysis_notes": "用中文生成约400-700字的分析笔记。优先保留：1. 本部分的核心论点；2. 重要事实、数据、案例和政策主张；3. 涉及中国、中美关系、国际竞争、科技、产业链、安全或国际秩序的内容；4. 作者的因果判断和政策建议。若本部分不涉及中国，不要强行添加中国内容。"
}}

报告标题：
{title}

当前部分：
第 {chunk_index}/{chunk_count} 部分

当前部分正文：
{content}
""".strip()
